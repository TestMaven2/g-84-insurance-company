import { Injectable } from '@nestjs/common';

@Injectable()
export class PromptService {
  createPromptForUserRequest(chunks: string[], request: string): string {
    return `Сгенерируй ответ, основываясь только на предоставленном контексте.
Дай только ответ, не упоминай в ответе контекст.

Контекст:

${chunks.join('\n\n')}

Конец контекста.

Вопрос:
${request}`;
  }

  createPromptForInsuranceType(request: string): string {
    return `Определи тип страхования, к которому относится вопрос пользователя.
Верни только одно из нижеперечисленных слов:

casco - если вопрос относится только к виду страхования КАСКО, то есть страхованию самого автомобиля как имущества без учёта гражданской ответственности
liability - если вопрос относится не к страхованию автомобиля как имущества, а только к виду страхования гражданской ответственности, то есть ответственности перед третьими лицами за причинённый ущерб
both - если вопрос однозначно относится к обоим видам страхования

ВАЖНО:
Если пользователь говорит о страховании автомобиля, машины или транспортного средства без упоминания ответственности перед третьими лицами, считай, что вопрос относится к casco.
Используй both только тогда, когда вопрос действительно затрагивает оба вида страхования.

Не дополняй ответ никакими лишними словами и символами, верни только одно слово.

Вопрос:
${request}`;
  }
}
